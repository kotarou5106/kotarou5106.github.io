"""Rebuild self-hosted reading fonts; no change to Hugo/Blog Writer builds.

Run: uv run --with fonttools --with brotli python scripts/prepare-reading-fonts.py
Sources are pinned; cached originals stay outside the repository.
"""

from collections import Counter
from hashlib import sha256
from io import BytesIO
from pathlib import Path
import re
from urllib.request import urlopen

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
CACHE = Path.home() / ".cache/kotarou-reading-fonts"
SOURCES = [
    ("ma-shan-zheng", "Kotarou Ma Shan Zheng", "mashanzheng", "MaShanZheng-Regular.ttf",
     "406197b91ff39a93061c2c2eeaee67ddf2ae1f0d", "400"),
    ("noto-sans-sc", "Kotarou Noto Sans SC", "notosanssc", "NotoSansSC[wght].ttf",
     "a85815a42757630ce188fdad368c2dfc444d4773", "400 700"),
]


def fetch(url, target):
    if not target.exists():
        target.write_bytes(urlopen(url.replace("[", "%5B").replace("]", "%5D")).read())
    return target.read_bytes()


def ranges(points):
    groups = []
    start = last = None
    for point in sorted(points):
        if last is not None and point == last + 1:
            last = point
            continue
        if start is not None:
            groups.append(f"U+{start:X}" + (f"-{last:X}" if last != start else ""))
        start = last = point
    if start is not None:
        groups.append(f"U+{start:X}" + (f"-{last:X}" if last != start else ""))
    return ",".join(groups)


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    output = ROOT / "static/fonts"
    output.mkdir(parents=True, exist_ok=True)
    stylesheet = ROOT / "assets/css/reading-fonts.css"
    previous = set(re.findall(r'/fonts/([\w-]+\.woff2)', stylesheet.read_text())) if stylesheet.exists() else set()
    generated = set()
    texts = [file.read_text() for file in sorted((ROOT / "content").rglob("*.md"))]
    headings = "\n".join(re.findall(r"(?m)^#{1,6}\s.*$", "\n".join(texts)))
    # Blog Writer also emits flow-style YAML front matter. Include it without
    # assuming the title occupies its own line; TOML front matter works too.
    headings += "\n".join(
        match.group(1) for text in texts
        if (match := re.match(r"(?:---|\+\+\+)\s*\n(.*?)\n(?:---|\+\+\+)", text, re.S))
    )
    body_frequency = Counter(map(ord, "\n".join(texts)))
    basic = set(range(0x20, 0x100)) | set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040))
    css = ["/* Generated by scripts/prepare-reading-fonts.py; see /fonts/README.md. */"]

    for slug, family, directory, filename, commit, weight in SOURCES:
        base = f"https://raw.githubusercontent.com/google/fonts/{commit}/ofl/{directory}"
        data = fetch(f"{base}/{filename}", CACHE / filename)
        license_text = fetch(f"{base}/OFL.txt", CACHE / f"{slug}-OFL.txt")
        (output / f"{slug}-OFL.txt").write_text(
            "\n".join(line.rstrip() for line in license_text.decode().splitlines()) + "\n"
        )
        font = TTFont(BytesIO(data), recalcTimestamp=False)
        if "fvar" in font:
            font = instantiateVariableFont(font, {"wght": (400, 700)}, inplace=True)
        buffer = BytesIO()
        font.save(buffer)
        prepared = buffer.getvalue()
        supported = set(font.getBestCmap())
        if slug == "ma-shan-zheng":
            core = (set(map(ord, headings)) | basic) & supported
        else:
            core = ({p for p, _ in body_frequency.most_common(1000)} | basic) & supported
        remaining = supported - core
        ordered = sorted(remaining, key=lambda p: (-body_frequency[p], p))
        # Full upstream coverage remains available for future posts. Disjoint
        # unicode-range faces avoid downloading the entire Chinese font.
        chunks = [core] + [set(ordered[i:i + 512]) for i in range(0, len(ordered), 512)]
        total = 0
        for index, points in enumerate(chunks):
            part = TTFont(BytesIO(prepared), recalcTimestamp=False)
            options = subset.Options()
            options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
            options.recalc_timestamp = False
            subsetter = subset.Subsetter(options=options)
            subsetter.populate(unicodes=points)
            subsetter.subset(part)
            part.flavor = "woff2"
            result = BytesIO()
            part.save(result)
            binary = result.getvalue()
            name = f"{slug}-{index:02d}-{sha256(binary).hexdigest()[:12]}.woff2"
            (output / name).write_bytes(binary)
            generated.add(name)
            total += len(binary)
            css.append(f'''@font-face {{
    font-family: "{family}";
    font-style: normal;
    font-weight: {weight};
    font-display: swap;
    src: url("/fonts/{name}") format("woff2");
    unicode-range: {ranges(points)};
}}''')
            if index == 0:
                print(f"{family}: core {len(points)} characters, {len(binary):,} bytes")
        assert set().union(*chunks) == supported
        print(f"{family}: {len(chunks)} shards, {total:,} bytes total; full upstream character coverage")
    stylesheet.write_text("\n\n".join(css) + "\n")
    for old in previous - generated:
        (output / old).unlink(missing_ok=True)


if __name__ == "__main__":
    main()
